"""Viewer access to PostFuego (post-fire debris-flow dynamic threshold) outputs. Runtime-safe: no ML libs.

Generated by scripts/evaluate_postfire.py, documented as an uncalibrated heuristic in every output.
"""
import json
from pathlib import Path

import folium
import numpy as np
import rasterio
from rasterio.transform import array_bounds
from rasterio.warp import Resampling, calculate_default_transform, reproject

REFERENCE_PATH = Path("catalog/postfire_reference.json")
SEMAPHORE_COLORS = {0: (198, 40, 40, 215), 1: (212, 160, 23, 210), 2: (46, 125, 50, 190)}  # rojo, amarillo, verde
SCENARIO_LABELS = {"enero": "31 de enero (seco, referencia histórica)", "octubre": "8 de octubre (saturado, referencia histórica)", "actual": "Esta semana (actualizar con lluvia reciente)"}


def postfire_reference():
    if REFERENCE_PATH.is_file():
        return json.loads(REFERENCE_PATH.read_text(encoding="utf-8"))
    return None


def semaphore_path(root, scenario_key):
    path = Path(root) / "postfire" / f"semaforo_{scenario_key}.tif"
    return path if path.is_file() else None


def read_mask(path):
    with rasterio.open(path) as src:
        return src.read(1), src.transform, str(src.crs), dict(src.tags())


def display_grid(mask, transform, crs, nodata=255, size=600):
    height, width = mask.shape
    bounds = array_bounds(height, width, transform)
    dst_transform, w, h = calculate_default_transform(crs, "EPSG:4326", width, height, *bounds, dst_width=size, dst_height=size)
    output = np.full((h, w), nodata, dtype=mask.dtype)
    reproject(mask, output, src_transform=transform, src_crs=crs, src_nodata=nodata, dst_transform=dst_transform, dst_crs="EPSG:4326", dst_nodata=nodata, resampling=Resampling.nearest)
    west, south, east, north = array_bounds(h, w, dst_transform)
    return output, [[south, west], [north, east]]


def semaphore_overlay(mask, transform, crs, name):
    grid, bounds = display_grid(mask, transform, crs)
    rgba = np.zeros(grid.shape + (4,), dtype="uint8")
    for value, color in SEMAPHORE_COLORS.items():
        rgba[grid == value] = color
    return folium.raster_layers.ImageOverlay(rgba, bounds=bounds, name=name, mercator_project=True)


def scenario_sentence(reference, scenario_key):
    if not reference:
        return "Sin referencia PostFuego calculada todavía."
    scenario = (reference.get("scenarios") or {}).get(scenario_key)
    if not scenario:
        return "Escenario no disponible."
    text = f"{scenario['label']}: umbral mediano {scenario['median_threshold_mm_30min']} mm en 30 minutos (mínimo {scenario['min_threshold_mm_30min']} mm en las sub-cuencas más sensibles)."
    if scenario.get("observed_30min_mm") is not None:
        veredicto = "superó el umbral" if scenario["would_have_triggered"] else "no superó el umbral"
        text += f" La lluvia observada ({scenario['observed_30min_mm']} mm/30min) {veredicto}."
    text += " Rojo: " + f"{100*scenario['fraction_rojo']:.0f}% del área; amarillo {100*scenario['fraction_amarillo']:.0f}%; verde {100*scenario['fraction_verde']:.0f}%."
    return text + " Heurística no calibrada; ver docs/postfuego_las_condes.md."
